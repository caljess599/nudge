#!/usr/bin/env python3
"""Generates Nudge's placeholder app icon for Android and iOS.

Design: two white rings on the app's teal, with a small dot sitting in a
gap of the outer ring (someone in a ring, getting a nudge).

Writes:
  android/app/src/main/res/drawable/ic_launcher_foreground.xml  (vector)
  android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml     (adaptive)
  android/app/src/main/res/values/ic_launcher_background.xml     (colour)
  android/app/src/main/res/mipmap-*/ic_launcher.png              (legacy)
  ios/Runner/Assets.xcassets/AppIcon.appiconset/*.png            (iOS)

Run from the repository root:  python3 tool/generate_icons.py
Needs Pillow (pip install pillow).
"""

import math
import os

from PIL import Image, ImageDraw

TEAL = (0x3B, 0x7A, 0x6E)
WHITE = (255, 255, 255)

# Geometry on Android's 108x108 adaptive-icon canvas. The centre 66x66 is
# the safe zone that is never masked, so everything stays within r=33.
C = 54.0
OUTER_R = 25.0
INNER_R = 13.5
STROKE = 5.0
DOT_ANGLE = -45.0  # degrees, 0 = 3 o'clock, negative = up (screen coords)
DOT_R = 4.75
GAP = 26.0  # degrees of outer ring left open on each side of the dot


def polar(r, degrees):
    a = math.radians(degrees)
    return C + r * math.cos(a), C + r * math.sin(a)


# ---------------------------------------------------------------- vector


def arc_path(r, start, sweep):
    """SVG/VectorDrawable path for an arc of radius r."""
    x0, y0 = polar(r, start)
    x1, y1 = polar(r, start + sweep)
    large = 1 if abs(sweep) > 180 else 0
    sweep_flag = 1 if sweep > 0 else 0
    return (
        f"M{x0:.3f},{y0:.3f} "
        f"A{r},{r} 0 {large},{sweep_flag} {x1:.3f},{y1:.3f}"
    )


def circle_path(r, cx=C, cy=C):
    return (
        f"M{cx - r:.3f},{cy:.3f} "
        f"a{r},{r} 0 1,0 {2 * r:.3f},0 "
        f"a{r},{r} 0 1,0 {-2 * r:.3f},0 Z"
    )


def foreground_vector():
    dot_x, dot_y = polar(OUTER_R, DOT_ANGLE)
    outer = arc_path(OUTER_R, DOT_ANGLE + GAP, 360 - 2 * GAP)
    inner = circle_path(INNER_R)
    dot = circle_path(DOT_R, dot_x, dot_y)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py. Placeholder icon: two rings
     and a dot. Also used as the monochrome (themed) icon. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:pathData="{outer}"
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="{STROKE}"
        android:strokeLineCap="round" />
    <path
        android:pathData="{inner}"
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="{STROKE}" />
    <path
        android:pathData="{dot}"
        android:fillColor="#FFFFFFFF" />
</vector>
"""


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""

BACKGROUND = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py. -->
<resources>
    <color name="ic_launcher_background">#{:02X}{:02X}{:02X}</color>
</resources>
""".format(*TEAL)

# ---------------------------------------------------------------- bitmaps


def render(size, canvas=108.0, circle_background=False):
    """Draws the icon at `size` px. `canvas` is how many of the 108 units
    the image spans (smaller = rings appear larger)."""
    ss = 4  # supersample for smooth edges
    px = size * ss
    scale = px / canvas
    offset = (canvas - 108.0) / 2  # centre the 108 canvas

    def p(x, y):
        return ((x + offset) * scale, (y + offset) * scale)

    if circle_background:
        img = Image.new("RGBA", (px, px), (0, 0, 0, 0))
        ImageDraw.Draw(img).ellipse((0, 0, px - 1, px - 1), fill=TEAL)
    else:
        img = Image.new("RGB", (px, px), TEAL)
    d = ImageDraw.Draw(img)
    w = STROKE * scale

    # Inner ring: a white disc with a teal disc inside.
    for r, colour in ((INNER_R + STROKE / 2, WHITE), (INNER_R - STROKE / 2, TEAL)):
        x0, y0 = p(C - r, C - r)
        x1, y1 = p(C + r, C + r)
        d.ellipse((x0, y0, x1, y1), fill=colour)
    # Outer ring with a gap: stamp round brushes along the centre line,
    # which also gives exact round caps at both ends.
    start, sweep = DOT_ANGLE + GAP, 360 - 2 * GAP
    steps = int(sweep * 10)
    r = w / 2
    for i in range(steps + 1):
        cx, cy = p(*polar(OUTER_R, start + sweep * i / steps))
        d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=WHITE)
    # The dot.
    cx, cy = p(*polar(OUTER_R, DOT_ANGLE))
    r = DOT_R * scale
    d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=WHITE)

    return img.resize((size, size), Image.LANCZOS)


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(content)


def main():
    res = "android/app/src/main/res"
    write(f"{res}/drawable/ic_launcher_foreground.xml", foreground_vector())
    write(f"{res}/mipmap-anydpi-v26/ic_launcher.xml", ADAPTIVE)
    write(f"{res}/values/ic_launcher_background.xml", BACKGROUND)

    # Legacy launcher icons (Android 7.x): a teal circle, rings filling it.
    for density, size in {
        "mdpi": 48,
        "hdpi": 72,
        "xhdpi": 96,
        "xxhdpi": 144,
        "xxxhdpi": 192,
    }.items():
        render(size, canvas=72, circle_background=True).save(
            f"{res}/mipmap-{density}/ic_launcher.png", optimize=True
        )

    # iOS: square, opaque (no alpha allowed), iOS rounds the corners.
    ios = "ios/Runner/Assets.xcassets/AppIcon.appiconset"
    for name in sorted(os.listdir(ios)):
        if not name.endswith(".png"):
            continue
        with Image.open(os.path.join(ios, name)) as old:
            size = old.size[0]
        render(size, canvas=80).save(os.path.join(ios, name), optimize=True)

    print("Icons written.")


if __name__ == "__main__":
    main()
